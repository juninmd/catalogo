test('service worker caches public catalog and works offline without caching private API', async ({ page, context }) => {
  await publicUI(page)
  await page.evaluate(async () => {
    const registration = await navigator.serviceWorker.ready
    if (!registration.active) await new Promise(resolve => navigator.serviceWorker.addEventListener('controllerchange', resolve, { once: true }))
    await new Promise(resolve => setTimeout(resolve, 1000))
  })
  const cacheCheck = await page.evaluate(async () => {
    const keys = await caches.keys()
    const cached = (await Promise.all(keys.map(async k => (await (await caches.open(k)).keys()).map(r => r.url)))).flat()
    return { api: cached.some(u => u.includes('/api/')), catalog: cached.some(u => u.endsWith('/catalog.json')) }
  })
  expect(cacheCheck).toEqual({ api: false, catalog: true })
  await page.unroute('**/api/catalog')
  await context.setOffline(true)
  const cachedCatalog = await page.evaluate(async () => (await (await fetch('/catalog.json')).json()).repos.length)
  expect(cachedCatalog).toBe(publicCatalog.repos.length)
  await page.reload()
  await expect(page.getByText('Você está offline', { exact: false })).toBeVisible()
  await expect(page.locator('.repo-card')).toHaveCount(24)
  await expect(page.getByText('Somente repositórios públicos', { exact: false })).toBeVisible()
  await context.setOffline(false)
})
test('PWA manifest and installability are accepted by the browser', async () => {
  const context = await chromium.launchPersistentContext('.catalog/pwa-check-' + Date.now(), { channel: 'msedge', headless: true, baseURL: 'http://127.0.0.1:4188' })
  try {
    const page = await context.newPage()
    await publicUI(page)
    await page.evaluate(() => navigator.serviceWorker.ready)
    const session = await context.newCDPSession(page)
    const manifest = await session.send('Page.getAppManifest')
    expect(manifest.errors).toEqual([])
    const data = JSON.parse(manifest.data)
    expect(data.display).toBe('standalone')
    expect(data.icons.map(i => i.sizes)).toEqual(['192x192', '512x512'])
    const eligibility = await session.send('Page.getInstallabilityErrors')
    expect(eligibility.installabilityErrors).toEqual([])
  } finally { await context.close() }
})
