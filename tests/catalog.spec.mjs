import { test, expect, chromium } from '@playwright/test'
import { readFile } from 'node:fs/promises'
const publicCatalog = JSON.parse(await readFile('docs/public/catalog.json', 'utf8'))
async function publicUI(page) {
  await page.route('**/api/catalog', route => route.fulfill({ json: publicCatalog }))
  await page.goto('/')
  await expect(page.locator('.loading')).toHaveCount(0)
  await expect(page.locator('.repo-card').first()).toBeVisible()
}
test('live private inventory, README and no-store access', async ({ request }) => {
  const response = await request.get('/api/catalog', { timeout: 180000 })
  expect(response.ok()).toBeTruthy()
  expect(response.headers()['cache-control']).toBe('no-store')
  const data = await response.json()
  expect(data.scope).toBe('private')
  expect(data.repos.some(r => r.private)).toBeTruthy()
  expect(data.repos.length).toBeGreaterThan(publicCatalog.repos.length)
  expect(data.repos.every(r => ['ok', 'missing', 'error'].includes(r.readme.status))).toBeTruthy()
  expect(data.repos.every(r => r.categories.length > 0)).toBeTruthy()
  expect(data.repos.every(r => ['application', 'library', 'example', 'prototype', 'documentation', 'assets', 'placeholder'].includes(r.projectType))).toBeTruthy()
  expect(JSON.stringify(data)).not.toMatch(/gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}/)
  console.log(JSON.stringify({ total: data.repos.length, private: data.repos.filter(r => r.private).length, readmes: data.repos.filter(r => r.readme.status === 'ok').length, missingReadmes: data.repos.filter(r => r.readme.status === 'missing').length, failedReadmes: data.repos.filter(r => r.readme.status === 'error').length, missingPurpose: data.repos.filter(r => r.purposeSource === 'Pendente').length }))
})
test('foreign origins and host names cannot read local data', async ({ request }) => {
  expect((await request.get('/api/catalog', { headers: { Origin: 'https://attacker.invalid' } })).status()).toBe(403)
  expect((await request.get('/api/catalog', { headers: { Host: 'attacker.invalid:4188' } })).status()).toBe(403)
  expect((await request.post('/api/catalog')).status()).toBe(405)
  expect((await request.get('/api/readme?repo=not-owned')).status()).toBe(404)
  expect((await request.post('/api/annotations', { data: { name: 'catalogo', purpose: 'forged', categories: [] }, headers: { Origin: 'https://attacker.invalid' } })).status()).toBe(403)
})
test('personal purpose and categories save locally and survive a new request', async ({ page, request }) => {
  const data = await (await request.get('/api/catalog')).json()
  const before = data.repos.find(r => r.name === 'catalogo')
  await page.goto('/')
  await page.getByLabel('Buscar aplicações').fill('catalogo')
  await page.locator('.repo-card h3 button').click()
  await page.getByRole('button', { name: 'Editar ficha pessoal' }).click()
  const purpose = 'Biblioteca pessoal de aplicações com READMEs e categorias. Validação de curadoria.'
  try {
    await page.getByLabel('Para que serve esta aplicação?').fill(purpose)
    await page.getByRole('button', { name: 'Salvar ficha' }).click()
    await expect(page.locator('.detail-purpose')).toHaveText(purpose)
    const after = await (await request.get('/api/catalog')).json()
    expect(after.repos.find(r => r.name === 'catalogo').purpose).toBe(purpose)
    const file = JSON.parse(await readFile('.catalog/annotations.json', 'utf8'))
    expect(file.catalogo.purpose).toBe(purpose)
  } finally {
    await request.post('/api/annotations', { headers: { Origin: 'http://127.0.0.1:4188' }, data: before.purposeSource === 'Anotação pessoal' ? { name: 'catalogo', purpose: before.purpose, categories: before.categories } : { name: 'catalogo', reset: true } })
  }
})
